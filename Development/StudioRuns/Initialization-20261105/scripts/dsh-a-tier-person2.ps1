$ErrorActionPreference = 'Stop'
$repo = 'D:\AI_Agent_Lab\rrpg_pilot\repo'
$artDir = Join-Path $repo 'Development\StudioRuns\Initialization-20261105\artifacts'
$srcDir = Join-Path $repo 'Development\SourceAssets\Village\A-Tier'
$logPath = Join-Path $artDir 'a-tier-person-v2.log'
New-Item -ItemType Directory -Force -Path $artDir | Out-Null
if (Test-Path -LiteralPath $logPath) { Remove-Item -LiteralPath $logPath -Force }
function Log([string]$m) { $line = ('[' + (Get-Date -Format 'HH:mm:ss') + '] ' + $m); Write-Output $line; Add-Content -LiteralPath $logPath -Value $line -Encoding UTF8 }

try {
  Add-Type -AssemblyName System.Drawing
  $bmp = New-Object System.Drawing.Bitmap(300, 200)
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
  $g.Clear([System.Drawing.Color]::Transparent)
  $skin = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 243, 219, 188))
  $tunic = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 58, 96, 176))
  $leg = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 38, 48, 72))
  $outline = New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(255, 20, 26, 40), 4)

  # legs
  $g.FillRectangle($leg, 120, 148, 24, 44)
  $g.FillRectangle($leg, 156, 148, 24, 44)
  # tunic (wide trapezoid, high contrast)
  $pts = New-Object 'System.Drawing.Point[]' 4
  $pts[0] = New-Object System.Drawing.Point(100, 74)
  $pts[1] = New-Object System.Drawing.Point(200, 74)
  $pts[2] = New-Object System.Drawing.Point(206, 152)
  $pts[3] = New-Object System.Drawing.Point(94, 152)
  $g.FillPolygon($tunic, $pts)
  # head
  $g.FillEllipse($skin, 124, 26, 52, 52)
  $g.DrawEllipse($outline, 124, 26, 52, 52)
  # arms hint
  $g.FillRectangle($tunic, 84, 84, 18, 52)
  $g.FillRectangle($tunic, 198, 84, 18, 52)

  $bmp.Save((Join-Path $srcDir 'person-a.png'), [System.Drawing.Imaging.ImageFormat]::Png)
  $bmp.Dispose()
  Log ('person-a.png regenerated bytes=' + (Get-Item (Join-Path $srcDir 'person-a.png')).Length)

  $exe = Join-Path $repo 'Tools\RRPG.ConfigCompiler\src\RRPG.ConfigCompiler\bin\Release\net10.0\rrpg-config.exe'
  $out = & $exe build --root $repo 2>&1
  $code = $LASTEXITCODE
  foreach ($l in $out) { if ($l -match 'RESULT|PASS|FAIL|updated|error') { Log ('  build| ' + $l) } }
  Log ('compiler exit=' + $code)
  if ($code -ne 0) { throw 'compiler build failed' }
  Log 'DONE'
  exit 0
}
catch {
  Log ('FATAL ' + $_.Exception.GetType().Name + ': ' + $_.Exception.Message)
  exit 1
}
